GLYPHS = {}
for _line in _RAW.strip().splitlines():
    _parts = _line.split()
    GLYPHS[_parts[0]] = _parts[1:8]
GLYPHS[" "] = ["....."] * 7


def text_cells(text, scale=1, gap=1):
    """Returns (width, height, cells) where cells are (col, row_from_top) pixels at the given scale."""
    cells = []
    x = 0
    for ch in text.upper():
        g = GLYPHS.get(ch, GLYPHS[" "])
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == "#":
                    for dx in range(scale):
                        for dy in range(scale):
                            cells.append((x + c * scale + dx, r * scale + dy))
        x += (5 + gap) * scale
    return x - gap * scale, 7 * scale, cells
